#!/usr/bin/env node
/**
 * TAP26-Junior app scanner (zero dependencies, cross-platform).
 *
 * Statically scans the Real World App and regenerates the knowledge inventories in
 * tap26/knowledge/generated/ (overwritten on every run — never hand-edit them):
 *
 *   api-routes.md       Express routes (METHOD full path, file:line, middleware, validators)
 *   ui-routes.md        react-router <Route path> → component (src/containers)
 *   ui-selectors.md     every data-test value in src/** grouped by component (dynamic = pattern)
 *   tests-inventory.md  Playwright + Cypress (e2e and component) specs with describe/test titles
 *   coverage-matrix.md  API route → spec files, data-test selector → spec files, uncovered summary
 *   state-machines.md   XState machines: ids, states, events, window services
 *
 * Usage:
 *   node tap26/scripts/scan-app.mjs            # write all files, print a summary
 *   node tap26/scripts/scan-app.mjs --json     # also print the summary as JSON (machines)
 *   node tap26/scripts/scan-app.mjs --out <dir># write somewhere else (default tap26/knowledge/generated)
 *
 * Output is deterministic (sorted) so diffs of the generated files show real app changes.
 * Exit codes: 0 ok · 1 unexpected error.
 */
import { mkdirSync, writeFileSync, readFileSync, existsSync } from "node:fs";
import { join, resolve, isAbsolute } from "node:path";
import { fileURLToPath } from "node:url";
import {
  SCRIPT_ROOT,
  scanApiRoutes,
  scanUiRoutes,
  scanSelectors,
  scanTests,
  scanMachines,
  scanWindowServices,
  buildApiIndex,
  routeCoverage,
  routeKey,
  selectorRefsOf,
  selectorReferenced,
  TEST_SOURCES,
  HELPER_SOURCES,
  uniqSorted,
} from "./lib/parse.mjs";

const ROOT = SCRIPT_ROOT;
const args = process.argv.slice(2);
if (args.includes("--help") || args.includes("-h")) {
  console.log(readFileSync(fileURLToPath(import.meta.url), "utf8").split("*/")[0]);
  process.exit(0);
}
const flag = (name) => {
  const i = args.indexOf(`--${name}`);
  return i >= 0 ? args[i + 1] : undefined;
};
const OUT = flag("out") ? (isAbsolute(flag("out")) ? flag("out") : resolve(process.cwd(), flag("out"))) : join(ROOT, "tap26", "knowledge", "generated");

const date = new Date().toISOString().slice(0, 16).replace("T", " ");
const header = (title, intro) => [`# ${title}`, ``, `> Generated by scan-app.mjs on ${date} UTC — do not edit (re-run \`node tap26/scripts/scan-app.mjs\`).`, ...(intro ? [``, intro] : []), ``];
const esc = (s) => String(s).replace(/\|/g, "\\|");
const code = (s) => `\`${esc(s)}\``;
const table = (cols, rows) => [`| ${cols.join(" | ")} |`, `|${cols.map(() => "---").join("|")}|`, ...rows.map((r) => `| ${r.join(" | ")} |`)];
const groupBy = (xs, key) => xs.reduce((acc, x) => ({ ...acc, [key(x)]: [...(acc[key(x)] || []), x] }), {});
const shortName = (file) => file.replace(/^playwright\/tests\//, "pw:").replace(/^cypress\/tests\//, "cy:").replace(/^src\//, "ct:");

// ---- scan -----------------------------------------------------------------------------

const routes = scanApiRoutes(ROOT);
const uiRoutes = scanUiRoutes(ROOT);
const selectors = scanSelectors(ROOT);
const tests = scanTests(ROOT, TEST_SOURCES);
const helpers = scanTests(ROOT, HELPER_SOURCES);
const machines = scanMachines(ROOT);
const services = scanWindowServices(ROOT);
const apiIndex = buildApiIndex(ROOT);

const testCov = routeCoverage(routes, tests, apiIndex);
const helperCov = routeCoverage(routes, helpers, apiIndex);
const selectorRefs = [...tests, ...helpers].map((t) => ({ file: t.file, refs: selectorRefsOf(t.text), helper: !t.titles.length }));
const selectorCov = selectors.map((sel) => {
  const hits = selectorRefs
    .map(({ file, refs, helper }) => ({ file, how: selectorReferenced(sel, refs), helper }))
    .filter((h) => h.how);
  return { sel, tests: hits.filter((h) => !h.helper), helpers: hits.filter((h) => h.helper) };
});

// ---- documents -------------------------------------------------------------------------

const apiRoutesDoc = () => {
  const byFile = groupBy(routes, (r) => r.file);
  return [
    ...header(
      "API routes (Express)",
      `${routes.length} routes parsed from \`backend/app.ts\` mount prefixes + \`backend/*-routes.ts\` + \`backend/auth.ts\`. ` +
        "`auth` = ensureAuthenticated (session cookie `connect.sid` required).",
    ),
    ...table(
      ["Method", "Path", "Source", "Auth", "Middleware / validators", "Notes"],
      routes.map((r) => [
        `**${r.method}**`,
        code(r.path),
        `${r.file}:${r.line}`,
        r.middleware.includes("ensureAuthenticated") ? "auth" : r.middleware.includes("passport.authenticate") ? "login" : "public",
        [...r.middleware.filter((m) => m !== "ensureAuthenticated"), ...r.validators].join(", ") || "—",
        r.notes.join("; ") || "",
      ]),
    ),
    ``,
    `## By source file`,
    ``,
    ...Object.keys(byFile)
      .sort()
      .flatMap((f) => [`- \`${f}\` — ${byFile[f].map((r) => `${r.method} ${r.path}`).join(", ")}`]),
    ``,
  ].join("\n");
};

const uiRoutesDoc = () =>
  [
    ...header(
      "UI routes (react-router)",
      `${uiRoutes.length} \`<Route>\`/\`<PrivateRoute>\` entries in \`src/containers/*.tsx\`. ` +
        "Nested switches (TransactionsContainer) render inside the `/(public|contacts|personal)?` route.",
    ),
    ...table(
      ["Path", "Element", "Component", "Exact", "Source"],
      [...uiRoutes]
        .sort((a, b) => a.file.localeCompare(b.file) || a.line - b.line)
        .map((r) => [code(r.path), r.element, r.redirect ? `Redirect → ${code(r.redirect)}` : r.component, r.exact ? "yes" : "no", `${r.file}:${r.line}`]),
    ),
    ``,
  ].join("\n");

const selectorsDoc = () => {
  const byComponent = groupBy(selectors, (s) => s.component);
  const dynamic = selectors.filter((s) => s.dynamic).length;
  return [
    ...header(
      "UI selectors (data-test)",
      `${selectors.length} \`data-test\` declarations (${uniqSorted(selectors.map((s) => s.value)).length} unique values, ${dynamic} dynamic patterns) ` +
        `in ${Object.keys(byComponent).length} components. Dynamic values are template literals: \`transaction-item-{id}\` ` +
        "means `transaction-item-${transaction.id}` — match them with `bySelLike` / `getBySelLike` or build the id.",
    ),
    ...Object.keys(byComponent)
      .sort()
      .flatMap((component) => [
        `## ${component}`,
        ``,
        `\`${byComponent[component][0].file}\``,
        ``,
        ...byComponent[component].map(
          (s) => `- ${code(s.value)}${s.dynamic ? " _(pattern)_" : ""}${s.kind !== "attr" ? ` _(${s.kind})_` : ""} — line ${s.line}`,
        ),
        ``,
      ]),
  ].join("\n");
};

const testsDoc = () => {
  const byFramework = groupBy(tests, (t) => t.framework);
  const label = { playwright: "Playwright (playwright/tests)", cypress: "Cypress e2e (cypress/tests)", "cypress-component": "Cypress component (src/**/*.cy.tsx)" };
  return [
    ...header("Tests inventory", "Titles are parsed statically (describe/context = suite, test/it = test); counts include skipped tests."),
    ...table(
      ["Framework", "Spec files", "Suites", "Tests"],
      Object.keys(byFramework)
        .sort()
        .map((fw) => [label[fw] || fw, byFramework[fw].length, byFramework[fw].reduce((n, t) => n + t.suites, 0), byFramework[fw].reduce((n, t) => n + t.tests, 0)]),
    ),
    ``,
    ...Object.keys(byFramework)
      .sort()
      .flatMap((fw) => [
        `## ${label[fw] || fw}`,
        ``,
        ...table(
          ["Spec", "Suites", "Tests"],
          byFramework[fw].map((t) => [code(t.file), t.suites, t.tests]),
        ),
        ``,
        ...byFramework[fw].flatMap((t) => [
          `### ${t.file}`,
          ``,
          ...t.titles.map((x) => `${"  ".repeat(x.level)}- ${x.kind === "suite" ? `**${esc(x.title)}**` : esc(x.title)} _(L${x.line})_`),
          ``,
        ]),
      ]),
  ].join("\n");
};

const coverageDoc = () => {
  const routeRows = routes.map((r) => {
    const t = testCov.get(routeKey(r));
    const h = helperCov.get(routeKey(r));
    const fmt = (set) => [...set].sort().map(shortName).join(", ");
    return { r, exact: [...t.exact].sort(), pathOnly: [...t.path].sort(), helpers: [...h.exact, ...h.path], cells: [`**${r.method}** ${code(r.path)}`, fmt(t.exact) || "—", fmt(t.path) || "—", uniqSorted([...h.exact, ...h.path]).map(shortName).join(", ") || "—"] };
  });
  const uncoveredRoutes = routeRows.filter((x) => !x.exact.length && !x.pathOnly.length && !x.helpers.length);
  const pathOnlyRoutes = routeRows.filter((x) => !x.exact.length && (x.pathOnly.length || x.helpers.length));
  const uncoveredSelectors = selectorCov.filter((x) => !x.tests.length && !x.helpers.length);
  const helperOnly = selectorCov.filter((x) => !x.tests.length && x.helpers.length);
  return [
    ...header(
      "Coverage matrix (static references)",
      "Static string matching — a reference means a spec *mentions* the route/selector, not that it asserts on it.\n" +
        "Route matching: `METHOD /path` in titles, `cy.request`/`cy.intercept` with a method, Playwright `endpoints.*` keys and `@api` functions (method-aware), " +
        "plus bare path strings (path only). Prefixes: `pw:` playwright/tests, `cy:` cypress/tests, `ct:` src component tests.",
    ),
    `## Summary`,
    ``,
    ...table(
      ["Item", "Total", "Referenced by a spec", "Only via helpers / path", "Unreferenced"],
      [
        ["API routes", routes.length, routeRows.filter((x) => x.exact.length).length, pathOnlyRoutes.length, uncoveredRoutes.length],
        ["data-test selectors", selectorCov.length, selectorCov.filter((x) => x.tests.length).length, helperOnly.length, uncoveredSelectors.length],
      ],
    ),
    ``,
    `### Unreferenced API routes`,
    ``,
    ...(uncoveredRoutes.length ? uncoveredRoutes.map((x) => `- **${x.r.method}** ${code(x.r.path)} — ${x.r.file}:${x.r.line}`) : ["- none"]),
    ``,
    `### Routes without a method-confirmed spec reference (path-only or helpers-only)`,
    ``,
    ...(pathOnlyRoutes.length
      ? pathOnlyRoutes.map((x) => `- **${x.r.method}** ${code(x.r.path)} — ${uniqSorted([...x.pathOnly, ...x.helpers]).map(shortName).join(", ")}`)
      : ["- none"]),
    ``,
    `### Unreferenced data-test selectors`,
    ``,
    ...(uncoveredSelectors.length ? uncoveredSelectors.map((x) => `- ${code(x.sel.value)} — ${x.sel.file}:${x.sel.line}`) : ["- none"]),
    ``,
    `## API route → specs`,
    ``,
    ...table(["Route", "Specs (method match)", "Specs (path only)", "Helpers"], routeRows.map((x) => x.cells)),
    ``,
    `## data-test selector → specs`,
    ``,
    "`exact` literal match · `pattern` template/prefix match · `partial` fragment (`bySelLike`, `getBySelLike`, `textbox`, composed ids).",
    ``,
    ...table(
      ["Selector", "Component", "Specs", "Helpers"],
      selectorCov.map(({ sel, tests: t, helpers: h }) => [
        code(sel.value),
        `${sel.component}:${sel.line}`,
        t.map((x) => `${shortName(x.file)} (${x.how})`).join(", ") || "—",
        h.map((x) => `${shortName(x.file)} (${x.how})`).join(", ") || "—",
      ]),
    ),
    ``,
  ].join("\n");
};

const machinesDoc = () => {
  const base = machines.find((m) => m.name === "dataMachine");
  return [
    ...header(
      "State machines (XState)",
      `${machines.length} machine modules in \`src/machines\`. Machines built with \`dataMachine(id)\` inherit its states/events ` +
        `(${base ? base.states.join(", ") : "idle, loading, …"}). Services exposed on \`window\` (only when \`window.Cypress\` is truthy) can be driven from tests.`,
    ),
    ...table(
      ["Module", "Machine id(s)", "States", "Events", "Exported services"],
      machines.map((m) => [
        code(m.name),
        m.ids.map(code).join(", ") || "—",
        m.states.length ? m.states.join(", ") : m.extendsDataMachine ? "_inherits dataMachine_" : "—",
        m.events.length ? m.events.join(", ") : m.extendsDataMachine ? "_inherits dataMachine_" : "—",
        m.services.join(", ") || "—",
      ]),
    ),
    ``,
    `## window services`,
    ``,
    ...table(
      ["Service", "Exposed in", "Machine module"],
      [...services].sort((a, b) => a.service.localeCompare(b.service) || a.file.localeCompare(b.file)).map((s) => [code(`window.${s.service}`), s.file, s.machines.join(", ")]),
    ),
    ``,
  ].join("\n");
};

// ---- write ------------------------------------------------------------------------------

const docs = {
  "api-routes.md": apiRoutesDoc(),
  "ui-routes.md": uiRoutesDoc(),
  "ui-selectors.md": selectorsDoc(),
  "tests-inventory.md": testsDoc(),
  "coverage-matrix.md": coverageDoc(),
  "state-machines.md": machinesDoc(),
};

let unchanged = 0;
try {
  mkdirSync(OUT, { recursive: true });
  // skip files whose content only differs by the "Generated … on <date>" line (keeps git diffs meaningful)
  const withoutDate = (t) => t.replace(/^> Generated by scan-app\.mjs on [^\n]*$/m, "");
  const written = Object.entries(docs).filter(([name, text]) => {
    const target = join(OUT, name);
    const body = text.endsWith("\n") ? text : `${text}\n`;
    if (existsSync(target) && withoutDate(readFileSync(target, "utf8")) === withoutDate(body)) return false;
    writeFileSync(target, body);
    return true;
  });
  unchanged = Object.keys(docs).length - written.length;
} catch (error) {
  console.error(`scan-app.mjs: cannot write to ${OUT}: ${error.message}`);
  process.exit(1);
}

const summary = {
  out: OUT,
  apiRoutes: routes.length,
  apiRoutesUnreferenced: routes.filter((r) => [testCov, helperCov].every((c) => !c.get(routeKey(r)).exact.size && !c.get(routeKey(r)).path.size)).length,
  uiRoutes: uiRoutes.length,
  selectors: selectors.length,
  selectorsUnique: uniqSorted(selectors.map((s) => s.value)).length,
  selectorsUnreferenced: selectorCov.filter((x) => !x.tests.length && !x.helpers.length).length,
  specFiles: Object.fromEntries(TEST_SOURCES.map((s) => [s.framework, tests.filter((t) => t.framework === s.framework).length])),
  tests: Object.fromEntries(TEST_SOURCES.map((s) => [s.framework, tests.filter((t) => t.framework === s.framework).reduce((n, t) => n + t.tests, 0)])),
  machines: machines.length,
  windowServices: uniqSorted(services.map((s) => s.service)).length,
  files: Object.keys(docs),
};

if (args.includes("--json")) console.log(JSON.stringify(summary, null, 2));
else
  console.log(
    [
      `scan-app: ${summary.files.length - unchanged} updated, ${unchanged} unchanged in ${OUT.startsWith(ROOT) ? OUT.slice(ROOT.length + 1).split("\\").join("/") : OUT}`,
      `  API routes        ${summary.apiRoutes} (${summary.apiRoutesUnreferenced} unreferenced by specs)`,
      `  UI routes         ${summary.uiRoutes}`,
      `  data-test         ${summary.selectors} declarations, ${summary.selectorsUnique} unique (${summary.selectorsUnreferenced} unreferenced)`,
      `  Playwright        ${summary.specFiles.playwright} specs / ${summary.tests.playwright} tests`,
      `  Cypress e2e       ${summary.specFiles.cypress} specs / ${summary.tests.cypress} tests`,
      `  Cypress component ${summary.specFiles["cypress-component"]} specs / ${summary.tests["cypress-component"]} tests`,
      `  XState machines   ${summary.machines} (${summary.windowServices} window services)`,
    ].join("\n"),
  );
